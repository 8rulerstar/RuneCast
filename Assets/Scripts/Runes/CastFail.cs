namespace RuneCast.Runes
{
    /// <summary>
    /// 룬이 안 나간 이유.
    ///
    /// **예전에는 이걸 번역된 문장으로 넘겼다.** 받는 쪽은
    /// `reason == Loc.T("hud.failMana")` 처럼 화면에 보이는 글자를 비교해서
    /// 마나 게이지를 튀게 할지, 어떤 튜토리얼을 띄울지 정했다.
    ///
    /// 지금 당장은 맞게 돈다. 하지만 **문구를 한 글자 고치면 조용히 꺼진다.**
    /// 두 사유의 문장이 우연히 같아져도 엉뚱한 쪽이 걸린다. 어느 쪽이든
    /// 오류 없이, 로그도 없이, 기능만 사라진다 — 제일 찾기 힘든 종류다.
    ///
    /// 글은 사람에게 보여주는 것이고 분기는 값으로 한다.
    /// </summary>
    public enum CastFail
    {
        None = 0,
        Ink,        // 잉크가 모자라 그리다 끊겼다
        Shape,      // 도형을 못 알아봤다
        NoCorpse,   // 되살릴 대상이 없다
        Mana,       // 마나가 모자라다
        Sealed,     // 이 판에서 잠긴 룬이다 (6장 봉인)
    }
}
